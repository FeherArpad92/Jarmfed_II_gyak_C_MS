/******************************************************************************
* Function: void timer_init(void)
* Description: Timer inicializálása CTC, 1 ms
* Input:
* Output:
* Notes:
******************************************************************************/
void timer_init(void)
{
	TCCR0A = (0<<WGM00) | (1<<WGM01) | (0<<CS02) | (1<<CS01) | (1<<CS00);
	OCR0A = 124;
	TIMSK0 = (1<<OCIE0A);
}

/******************************************************************************
* Function: void external_interrupt_init(void)
* Description: Küls? megszakítások inicializálása
* Input:
* Output:
* Notes:
******************************************************************************/
void external_interrupt_init(void)
{
	EICRA = (0<<ISC00) | (1<<ISC01);
	EIMSK = (1<<INT0);
}

/******************************************************************************
* Function: void ad_init(void)
* Description: A/D inicializálása
* Input:
* Output:
* Notes:
******************************************************************************/
void ad_init(void)
{
	ADMUX = 0;
	ADCSRA = (1<<ADPS0) | (1<<ADPS1) | (1<<ADPS2) | (1<<ADEN) | (1<<ADIE) | (1<<ADSC);
	ADCSRB = 0;
	
}

/******************************************************************************
* Function: void uart_0_init(uint16_t baud)
* Description: UART 0 inicializálása
* Input:
* Output:
* Notes:
******************************************************************************/
void uart_0_init(uint16_t baud)
{
	UBRR0H = (uint8_t)(baud>>8);
	UBRR0L = (uint8_t)(baud);
	
	UCSR0A =0;
	UCSR0B = (1<<RXEN) | (1<<TXEN) | (1<<RXCIE0);
	UCSR0C = (1<<UCSZ1) | (1<<UCSZ0);
}


